/*
  Decipher's first data: TAC (an IMEI's first 8 digits) → model, from the work orders the tracker has kept.

    node worker/import/tac-seed.mjs [path/to/workorders.db] [out.sql]
    cd worker && npx wrangler d1 execute aethernet-waymark --remote --file import/tac-seed.sql

  Reads ubif-workorders' database READ-ONLY (the newest snapshot of each work order: CustomerDevice.imei and its
  DeviceCatalog/DeviceModel). Writes only model-level rows: the 8-digit TAC, the model's id, name and manufacturer, the color
  (the catalog name after the model name: "iPhone 16 Pro Desert Titanium" → "Desert Titanium"), a count, and the store's id.
  A full IMEI, serial, customer or work order number never reaches the output. The .sql is git-ignored: delete it after applying.
  Additive: tac_models / tac_stores are only inserted into (counts add up if a row exists). Run it once per database.
*/
import { DatabaseSync } from 'node:sqlite';
import { writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const db = process.argv[2] || join(homedir(), 'Scripts/ubif-workorders/workorders.db');
const out = process.argv[3] || join(dirname(fileURLToPath(import.meta.url)), 'tac-seed.sql');
const d = new DatabaseSync(db, { readOnly: true });

const luhn = (s) => { let sum = 0; for (let i = 0; i < s.length; i++) { let n = Number(s[(s.length - 1) - i]); if (i % 2) { n *= 2; if (n > 9) n -= 9; } sum += n; } return sum % 10 === 0; };
const clean = (v, max) => String(v == null ? '' : v).replace(/[\u0000-\u001f\u007f]/g, '').replace(/\s+/g, ' ').trim().slice(0, max);
const q = (v) => (v == null ? 'NULL' : typeof v === 'number' ? String(v) : "'" + String(v).replace(/'/g, "''") + "'");

const rows = d.prepare('SELECT s.raw_json FROM workorder_snapshots s JOIN (SELECT workorder_id, MAX(id) m FROM workorder_snapshots GROUP BY workorder_id) x ON s.id = x.m').all();
const models = new Map(); // "tac|model|color" → row
const stores = new Map(); // "tac|store" → count
const tacs = new Map();   // tac → Set of model ids (conflicts)
let withImei = 0, badCheck = 0, noModel = 0;
for (const { raw_json } of rows) {
  let w; try { w = JSON.parse(raw_json).workorder.workorder; } catch { continue; }
  const cd = (w && w.CustomerDevice) || {}, imei = String(cd.imei || '').trim();
  if (!/^\d{15}$/.test(imei)) continue;
  withImei++;
  if (!luhn(imei)) { badCheck++; continue; }
  const dc = cd.DeviceCatalog || {}, dm = dc.DeviceModel || {};
  const id = Number(dc.deviceModelId), name = clean(dm.modelNumber || dc.name, 120);
  if (!Number.isInteger(id) || id < 1 || !name || /^other device/i.test(name)) { noModel++; continue; } // "Other Device" is a placeholder, not a model
  const full = clean(dc.name, 160), color = full.startsWith(name) ? clean(full.slice(name.length), 60) : '';
  const tac = imei.slice(0, 8), key = tac + '|' + id + '|' + color;
  const r = models.get(key) || { tac, id, color, name, mfr: clean(dm.DeviceManufacturer && dm.DeviceManufacturer.name, 60) || null, n: 0 };
  r.n++; models.set(key, r);
  const sk = tac + '|' + Number(w.storeId); if (Number(w.storeId) > 0) stores.set(sk, (stores.get(sk) || 0) + 1);
  (tacs.get(tac) || tacs.set(tac, new Set()).get(tac)).add(id);
}

const at = new Date().toISOString();
const sql = ['-- Decipher seed: TAC → model rows only (generated by tac-seed.mjs; delete after applying)'];
for (const r of models.values()) {
  sql.push(`INSERT INTO tac_models (tac, device_model_id, color, model_name, manufacturer, count, updated_at) VALUES (${q(r.tac)}, ${r.id}, ${q(r.color)}, ${q(r.name)}, ${q(r.mfr)}, ${r.n}, ${q(at)}) ` +
    'ON CONFLICT (tac, device_model_id, color) DO UPDATE SET count = count + excluded.count, updated_at = excluded.updated_at;');
}
for (const [k, n] of stores) {
  const [tac, store] = k.split('|');
  sql.push(`INSERT INTO tac_stores (tac, store, count) VALUES (${q(tac)}, ${Number(store)}, ${n}) ON CONFLICT (tac, store) DO UPDATE SET count = count + excluded.count;`);
}
writeFileSync(out, sql.join('\n') + '\n');
const conflicts = [...tacs.values()].filter((s) => s.size > 1).length;
console.log(JSON.stringify({ workOrders: rows.length, withImei, badCheckDigit: badCheck, noModel, tacs: tacs.size, models: new Set([...models.values()].map((r) => r.id)).size, modelColorRows: models.size, tacsWithConflicts: conflicts, out }));
