/*
  Decipher's community suggestions: the Osmocom TAC database (https://tacdb.osmocom.org/, CC BY-SA 3.0,
  © Harald Welte and contributors) as a one-time import into its OWN table, osmocom_tac(tac, brand, model).
  Never merged into tac_models (what stores have seen); the Worker only offers it when tac_models has no model for a TAC.

    node worker/import/osmocom.mjs [tacdb.sqlite3] [out.sql]
    cd worker && npx wrangler d1 execute aethernet-waymark --remote --file import/osmocom.sql

  Without a path it downloads the export (https://tacdb.osmocom.org/export/tacdb.sqlite3, about 4 MB) into the temp folder; the site's
  certificate is for another hostname, so certificate checking is off for that one public download. Re-runnable: rows are replaced by TAC.
  The download is never kept in the repo and the .sql is git-ignored (delete it after applying). Contributors and links aren't copied.
*/
import { DatabaseSync } from 'node:sqlite';
import { mkdirSync, writeFileSync, createWriteStream } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import https from 'node:https';

const URL_ = 'https://tacdb.osmocom.org/export/tacdb.sqlite3';
const out = process.argv[3] || join(dirname(fileURLToPath(import.meta.url)), 'osmocom.sql');

async function download() {
  const dir = join(tmpdir(), 'ae-osmocom'); mkdirSync(dir, { recursive: true });
  const file = join(dir, 'tacdb.sqlite3');
  await new Promise((resolve, reject) => https.get(URL_, { rejectUnauthorized: false }, (res) => {
    if (res.statusCode !== 200) return reject(new Error('HTTP ' + res.statusCode));
    const f = createWriteStream(file); res.pipe(f); f.on('finish', () => f.close(resolve)); f.on('error', reject);
  }).on('error', reject));
  return file;
}

const src = process.argv[2] || await download();
const d = new DatabaseSync(src, { readOnly: true });
const clean = (v, max) => String(v == null ? '' : v).replace(/[\u0000-\u001f\u007f]/g, '').replace(/\s+/g, ' ').trim().slice(0, max);
const q = (v) => (v ? "'" + v.replace(/'/g, "''") + "'" : 'NULL');

const rows = d.prepare('SELECT t.tac AS tac, b.name AS brand, m.name AS model FROM tac t JOIN model m ON m.id = t.model LEFT JOIN brand b ON b.id = m.brand').all();
const byTac = new Map();
for (const r of rows) if (/^\d{8}$/.test(r.tac) && clean(r.model, 120)) byTac.set(r.tac, [clean(r.brand, 60), clean(r.model, 120)]);
const list = [...byTac];
const sql = ['-- Decipher: Osmocom TAC database import (generated by osmocom.mjs; delete after applying)'];
for (let i = 0; i < list.length; i += 200) {
  sql.push('INSERT INTO osmocom_tac (tac, brand, model) VALUES ' + list.slice(i, i + 200).map(([t, [b, m]]) => `('${t}', ${q(b)}, ${q(m)})`).join(', ') +
    ' ON CONFLICT (tac) DO UPDATE SET brand = excluded.brand, model = excluded.model;');
}
writeFileSync(out, sql.join('\n') + '\n');
console.log(JSON.stringify({ source: rows.length, tacs: byTac.size, out }));
